def build_role_user_prompt(logic_ir_json: str) -> str:
    return f"""
다음 Logic IR을 기반으로 설명을 생성하라.

공통 규칙:
- 반드시 한국어로 작성
- 코드 설명 금지
- Logic IR에 있는 내용만 사용 (추측 금지)

작성 방식:
- summary: 전체 로직을 직군 관점에서 한 줄 요약
- key_points: 핵심 포인트 3~5개
- questions_to_confirm: 해당 직군이 실제로 확인해야 할 질문

추가 요구:
- 조건, 결과, 예외 케이스를 반드시 반영
- 직군 특성이 드러나도록 작성

출력 형식(JSON):
{{
  "title": "...",
  "summary": "...",
  "key_points": ["..."],
  "questions_to_confirm": ["..."]
}}

Logic IR:
{logic_ir_json}
"""